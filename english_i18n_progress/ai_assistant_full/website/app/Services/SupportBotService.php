    /**
     * إرجاع أكثر المقالات ارتباطًا بالسؤال.
     */
    public function findRelevantArticles(
        string $message,
        int $limit = 8
    ): Collection {
        $limit = max(
            1,
            min($limit, 12)
        );

        $words = $this->extractWords($message);

        if ($words->isEmpty()) {
            return collect();
        }

        $articles = KnowledgeBaseArticle::query()
            ->where('is_active', true)
            ->where('ai_enabled', true)
            ->get();

        return $articles
            ->map(function (
                KnowledgeBaseArticle $article
            ) use ($words) {
                return [
                    'article' => $article,
                    'score' => $this->calculateScore(
                        $article,
                        $words
                    ),
                ];
            })
            ->filter(
                fn (array $item) =>
                    $item['score'] > 0
            )
            ->sortByDesc('score')
            ->take($limit)
            ->pluck('article')
            ->values();
    }

    /**
     * حساب درجة ارتباط المقالة بالسؤال.
     */
    private function calculateScore(
        KnowledgeBaseArticle $article,
        Collection $words
    ): float {
        $questionText = $this->normalizeArabicText(
            (string) $article->question
        );

        $keywordsText = $this->normalizeArabicText(
            $this->normalizeKeywords(
                $article->keywords
            )
        );

        $answerText = $this->normalizeArabicText(
            (string) $article->answer
        );

        $score = 0;

        foreach ($words as $word) {
            if (
                Str::contains(
                    $questionText,
                    $word
                )
            ) {
                $score += 4;
            }

            if (
                Str::contains(
                    $keywordsText,
                    $word
                )
            ) {
                $score += 3;
            }

            if (
                Str::contains(
                    $answerText,
                    $word
                )
            ) {
                $score += 1;
            }
        }

        if (
            isset($article->priority)
            && is_numeric($article->priority)
        ) {
            $score +=
                ((float) $article->priority) * 0.1;
        }

        return $score;
    }

    /**
     * تحويل الكلمات المفتاحية إلى نص.
     */
    private function normalizeKeywords(
        mixed $keywords
    ): string {
        if (is_array($keywords)) {
            return collect($keywords)
                ->filter()
                ->map(
                    fn ($keyword) =>
                        trim((string) $keyword)
                )
                ->implode(', ');
        }

        if (! is_string($keywords)) {
            return '';
        }

        $keywords = trim($keywords);

        if ($keywords === '') {
            return '';
        }

        $decoded = json_decode(
            $keywords,
            true
        );

        if (
            json_last_error()
                === JSON_ERROR_NONE
            && is_array($decoded)
        ) {
            return collect($decoded)
                ->filter()
                ->map(
                    fn ($keyword) =>
                        trim((string) $keyword)
                )
                ->implode(', ');
        }

        return $keywords;
    }

    /**
     * استخراج الكلمات المهمة من سؤال المستخدم.
     */
    private function extractWords(
        string $message
    ): Collection {
        $message = $this->normalizeArabicText(
            $message
        );

        $message = preg_replace(
            '/[^\p{Arabic}\p{L}\p{N}\s]/u',
            ' ',
            $message
        );

        $ignoredWords = [
            'كيف',
            'شو',
            'ماذا',
            'وين',
            'اين',
            'هل',
            'في',
            'من',
            'على',
            'الي',
            'الى',
            'عن',
            'انا',
            'بدي',
            'اريد',
            'عندي',
            'ممكن',
            'لو',
            'ما',
            'هو',
            'هي',
            'هذا',
            'هذه',
            'مع',
            'او',
            'ثم',
            'كل',
            'اي',
            'ليش',
            'ليه',
            'طريقه',
        ];

        return collect(
            preg_split(
                '/\s+/u',
                $message
            )
        )
            ->map(
                fn ($word) =>
                    trim((string) $word)
            )
            ->filter(
                fn ($word) =>
                    mb_strlen($word) >= 2
            )
            ->reject(
                fn ($word) =>
                    in_array(
                        $word,
                        $ignoredWords,
                        true
                    )
            )
            ->unique()
            ->values();
    }

    /**
     * توحيد الكتابة العربية لتقوية البحث والتعرف على النوايا.
     */
    private function normalizeArabicText(
        string $text
    ): string {
        $text = Str::lower(
            trim($text)
        );

        return str_replace(
            [
                'أ',
                'إ',
                'آ',
                'ة',
                'ى',
                'ؤ',
                'ئ',
            ],
            [
                'ا',
                'ا',
                'ا',
                'ه',
                'ي',
                'و',
                'ي',
            ],
            $text
        );
    }
