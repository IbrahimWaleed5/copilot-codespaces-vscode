    /**
     * البحث التقليدي عن أفضل إجابة كحل احتياطي.
     */
    public function findAnswer(string $message): ?array
    {
        $words = $this->extractWords($message);

        if ($words->isEmpty()) {
            return null;
        }

        $articles = KnowledgeBaseArticle::query()
            ->where('is_active', true)
            ->where('ai_enabled', true)
            ->get();

        $bestArticle = null;
        $bestScore = 0;

        foreach ($articles as $article) {
            $score = $this->calculateScore($article, $words);

            if ($score > $bestScore) {
                $bestScore = $score;
                $bestArticle = $article;
            }
        }

        if (! $bestArticle || $bestScore < 1) {
            return null;
        }

        $confidence = min(
            1,
            $bestScore / max($words->count(), 1)
        );

        if ($confidence < 0.35) {
            return null;
        }

        $bestArticle->increment('views');

        return [
            'article' => $bestArticle,
            'answer' => $bestArticle->answer,
            'confidence' => round($confidence, 4),
        ];
    }

