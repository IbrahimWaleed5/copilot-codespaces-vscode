- هذه المعلومات تخص ظهور الموقع لمحركات البحث، ولا تعني ضمان ترتيب معين في Google.

16) المهندسون والأعمال
- المهندس يستطيع إضافة أعماله وصوره ومعلوماته حسب الصلاحيات.
- العميل يستطيع تصفح مكتبة الأعمال وصفحات المهندسين واختيار مهندس عندما يكون المسار متاحًا.
