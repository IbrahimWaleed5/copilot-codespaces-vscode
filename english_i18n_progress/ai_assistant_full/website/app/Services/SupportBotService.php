- الحساب المعلّق قد يملك مسار اعتراض مخصص.
- لا تساعد على تجاوز الرقابة أو الصلاحيات أو الوصول إلى بيانات مستخدم آخر.

20) الدعم الفني والمساعد الذكي
- المساعد الذكي هو "مساعد منصة الوليد الهندسية الهندسي".
